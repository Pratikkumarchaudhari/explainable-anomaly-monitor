"""Export the exact synthetic inputs and their provenance for independent review."""
import json
from pathlib import Path
from monitor import sample, FEATURES

def export(root=None):
    root = Path(root or Path(__file__).resolve().parent)
    folder = root / 'data'
    folder.mkdir(exist_ok=True)
    specs = [('train',1200,11,0),('calibration',400,22,0),('test',600,33,.08)]
    manifest = {'source':'Generated by monitor.sample; no external or employer data',
                'features':FEATURES,'splits':[]}
    for name,n,seed,rate in specs:
        frame = sample(n,seed,rate)
        frame.to_csv(folder / (name+'.csv'),index=False)
        manifest['splits'].append({'file':name+'.csv','rows':n,'seed':seed,
                                  'injected_anomalies':int(frame.injected_anomaly.sum())})
    (folder/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    return manifest

if __name__ == '__main__':
    print(json.dumps(export(),indent=2))
